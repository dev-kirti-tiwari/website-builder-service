CREATE TABLE pages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL,
  name VARCHAR(180) NOT NULL,
  slug VARCHAR(200) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
  revision INTEGER NOT NULL DEFAULT 1,
  created_by BIGINT,
  updated_by BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  deleted_at TIMESTAMPTZ NULL,
  CHECK (status IN ('DRAFT', 'PUBLISHED')),
  CHECK (revision >= 1)
);
CREATE UNIQUE INDEX pages_workspace_slug_active_uq ON pages (workspace_id, slug) WHERE deleted_at IS NULL;
CREATE INDEX pages_workspace_deleted_idx ON pages (workspace_id, deleted_at);

CREATE TABLE page_sections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  page_id BIGINT NOT NULL REFERENCES pages(id),
  workspace_id BIGINT NOT NULL,
  section_type VARCHAR(40) NOT NULL,
  position INTEGER NOT NULL CHECK (position >= 1),
  variant VARCHAR(60),
  visible BOOLEAN NOT NULL DEFAULT TRUE,
  configuration JSONB NOT NULL DEFAULT '{}'::jsonb,
  responsive JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX page_sections_order_idx ON page_sections (workspace_id, page_id, position);

CREATE TABLE page_layouts (
  page_id BIGINT PRIMARY KEY REFERENCES pages(id),
  workspace_id BIGINT NOT NULL,
  layout JSONB NOT NULL DEFAULT '{}'::jsonb,
  responsive JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE page_revisions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  page_id BIGINT NOT NULL REFERENCES pages(id),
  workspace_id BIGINT NOT NULL,
  revision_number INTEGER NOT NULL,
  snapshot JSONB NOT NULL,
  created_by BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (page_id, revision_number)
);

CREATE TABLE page_audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id BIGINT NOT NULL,
  actor_id BIGINT,
  action VARCHAR(60) NOT NULL,
  resource VARCHAR(120),
  request_id VARCHAR(64),
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
