CREATE TABLE section_contents (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id   BIGINT       NOT NULL,
  page_id        BIGINT       NOT NULL,
  section_id     BIGINT       NOT NULL,
  section_type   VARCHAR(40)  NOT NULL,
  schema_version INTEGER      NOT NULL DEFAULT 1,
  content        JSONB        NOT NULL DEFAULT '{}'::jsonb,
  revision       INTEGER      NOT NULL DEFAULT 1,
  created_by     BIGINT,
  updated_by     BIGINT,
  created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  deleted_at     TIMESTAMPTZ  NULL,
  CHECK (schema_version >= 1),
  CHECK (revision >= 1)
);

-- one non-deleted content record per workspace + section
CREATE UNIQUE INDEX uq_section_contents_active_section
  ON section_contents (workspace_id, section_id) WHERE deleted_at IS NULL;

-- bulk page reads
CREATE INDEX idx_section_contents_workspace_page
  ON section_contents (workspace_id, page_id) WHERE deleted_at IS NULL;
