CREATE TABLE content_revisions (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id       BIGINT      NOT NULL,
  section_content_id BIGINT      NOT NULL REFERENCES section_contents(id),
  page_id            BIGINT      NOT NULL,
  section_id         BIGINT      NOT NULL,
  revision_number    INTEGER     NOT NULL,
  schema_version     INTEGER     NOT NULL,
  snapshot           JSONB       NOT NULL,
  created_by         BIGINT,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_content_revisions_content_revision UNIQUE (section_content_id, revision_number)
);

CREATE INDEX idx_content_revisions_lookup
  ON content_revisions (workspace_id, section_content_id, revision_number DESC);

-- snapshots are immutable: block UPDATE and DELETE
CREATE FUNCTION content_revisions_immutable() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION 'content_revisions rows are immutable';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_content_revisions_immutable
  BEFORE UPDATE OR DELETE ON content_revisions
  FOR EACH ROW EXECUTE FUNCTION content_revisions_immutable();
