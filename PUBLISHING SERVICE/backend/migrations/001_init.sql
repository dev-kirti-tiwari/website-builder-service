-- Stand-in tables for the Website service (remove when integrating the real website-client).
CREATE TABLE IF NOT EXISTS wb_websites (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id BIGINT NOT NULL,
  organization_id BIGINT NOT NULL,
  name TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'unpublished' CHECK (status IN ('unpublished','published')),
  active_release_id BIGINT,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS wb_websites_scope ON wb_websites (tenant_id, organization_id);

CREATE TABLE IF NOT EXISTS wb_revisions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  website_id BIGINT NOT NULL REFERENCES wb_websites(id),
  content JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS publishing_releases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id BIGINT NOT NULL,
  organization_id BIGINT NOT NULL,
  website_id BIGINT NOT NULL REFERENCES wb_websites(id),
  revision_id BIGINT NOT NULL REFERENCES wb_revisions(id),
  deployment_id BIGINT,
  snapshot JSONB NOT NULL,
  content_hash TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'building' CHECK (status IN ('building','ready','active','superseded','failed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  activated_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS releases_scope ON publishing_releases (tenant_id, organization_id, website_id, id DESC);

CREATE TABLE IF NOT EXISTS publishing_deployments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id BIGINT NOT NULL,
  organization_id BIGINT NOT NULL,
  website_id BIGINT NOT NULL REFERENCES wb_websites(id),
  revision_id BIGINT NOT NULL,
  release_id BIGINT REFERENCES publishing_releases(id),
  kind TEXT NOT NULL CHECK (kind IN ('publish','rollback','unpublish')),
  status TEXT NOT NULL DEFAULT 'queued' CHECK (status IN
    ('queued','validating','preparing','deploying','verifying','activating','propagating','succeeded','failed')),
  propagation_status TEXT NOT NULL DEFAULT 'not_started' CHECK (propagation_status IN ('not_started','completed','failed')),
  requested_by TEXT NOT NULL,
  reason TEXT,
  error_code TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS deployments_scope ON publishing_deployments (tenant_id, organization_id, website_id, id DESC);
CREATE INDEX IF NOT EXISTS deployments_status ON publishing_deployments (status, created_at);

CREATE TABLE IF NOT EXISTS publishing_deployment_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  deployment_id BIGINT NOT NULL REFERENCES publishing_deployments(id),
  attempt_number INT NOT NULL,
  status TEXT NOT NULL DEFAULT 'running' CHECK (status IN ('running','succeeded','failed')),
  provider_ref TEXT,
  error_code TEXT,
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  ended_at TIMESTAMPTZ,
  UNIQUE (deployment_id, attempt_number)
);

CREATE TABLE IF NOT EXISTS publishing_deployment_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  deployment_id BIGINT NOT NULL REFERENCES publishing_deployments(id),
  stage TEXT NOT NULL,
  message TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS publishing_idempotency_keys (
  scope TEXT NOT NULL,
  key_hash TEXT NOT NULL,
  request_hash TEXT NOT NULL,
  status_code INT,
  response JSONB,
  expires_at TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (scope, key_hash)
);

CREATE TABLE IF NOT EXISTS publishing_outbox_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_type TEXT NOT NULL,
  aggregate_id BIGINT NOT NULL,
  payload JSONB NOT NULL DEFAULT '{}',
  attempts INT NOT NULL DEFAULT 0,
  locked_until TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  processed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS outbox_pending ON publishing_outbox_events (id) WHERE processed_at IS NULL;

CREATE TABLE IF NOT EXISTS publishing_preview_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id BIGINT NOT NULL,
  organization_id BIGINT NOT NULL,
  website_id BIGINT NOT NULL REFERENCES wb_websites(id),
  revision_id BIGINT NOT NULL REFERENCES wb_revisions(id),
  token_hash TEXT NOT NULL,
  created_by TEXT NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  revoked_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS publishing_audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id BIGINT NOT NULL,
  organization_id BIGINT NOT NULL,
  website_id BIGINT,
  actor TEXT NOT NULL,
  action TEXT NOT NULL,
  metadata JSONB NOT NULL DEFAULT '{}',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
